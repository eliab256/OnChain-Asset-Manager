// Allows strings and string-returning functions at any depth.
type DictShape = { [key: string]: string | ((...args: never[]) => string) | DictShape };

type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : { [K in keyof T]: Widen<T[K]> };

export type Messages = Widen<typeof en>;
